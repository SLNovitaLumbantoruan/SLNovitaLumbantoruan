// Problem 1 - String Concatenation
let firstName = 'John';
let LastName = 'Doe';
let bornYear = 1998;

// Menghitung umur dari tahun sekarang
let currentYear = new Date().getFullYear();
let age = currentYear - bornYear;

// Menampilkan hasil
console.log("Hello, " + firstName + " " + LastName + "! You are " + age + " years old.");

